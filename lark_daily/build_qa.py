def clean(c):
    if not c:
        return ''
    c = re.sub(r'!\[Image\]\([^)]*\)', '[图片]', c)
    c = re.sub(r'\[Image: [^\]]*\]', '[图片]', c)
    c = re.sub(r'<file key="[^"]*" name="([^"]*)"/>', r'[文件] \1', c)
    c = re.sub(r'<video key="[^"]*" name="([^"]*)"[^>]*/>', r'[视频] \1', c)
    c = re.sub(r'<calendar_share[^>]*>', '[日程] ', c)
    c = re.sub(r'<forwarded_messages>', '[合并转发]', c)
    c = re.sub(r'\[Sticker\]', '[表情]', c)
    c = re.sub(r':Lark_Emoji_[A-Za-z0-9_]+:', '', c)
    c = re.sub(r'<[^>]+>', '', c)
    return c.strip()

idx = defaultdict(list)
for m in msgs:
    s = (m.get('sender') or {}).get('name', '')
    idx[(m['chat_id'], m['create_time'][11:16], s)].append(m)

used = set()

def find(chat_key, hm, sender):
    key = (CH[chat_key], hm, sender)
    cands = idx.get(key) or []
    for m in cands:
        if m['message_id'] not in used:
            used.add(m['message_id'])
            return m
    if cands:
        return cands[0]
    for (cid, t, s), lst in idx.items():
        if cid == CH[chat_key] and t == hm and lst:
            return lst[0]
    raise KeyError(f'not found: {chat_key} {hm} {sender}')

