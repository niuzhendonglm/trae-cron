missing = []
for chat_id, asker, sub, fb, q, a, replier, qtype, ai in QA:
    m = find(chat_id, asker, sub)
    if m is None and fb:
        m = find(chat_id, fb[0], fb[1])
    if m is None:
        missing.append((asker, sub))
        continue
    text = m['text'][:2000]
    answer = ai if ai else a
    rows.append({'fields': {
        'Question': q, 'Answer': answer, '提问人': asker, '回复人': replier,
        '问题日期': iso(m), '问题类型': qtype,
        'AI回复': ai if ai else '', '文本': text}})

