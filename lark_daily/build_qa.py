records = []
problems = []
for i, sp in enumerate(SPEC):
    try:
        qm = find(sp['c'], sp['q'][0], sp['q'][1])
    except KeyError as e:
        problems.append(str(e))
        continue
    asker = (qm.get('sender') or {}).get('name', '')
    raw = qm.get('content') or ''
    question = clean(raw) or '[图片]'
    if sp.get('a'):
        parts, repliers = [], []
        for hm, snd in sp['a']:
            try:
                am = find(sp['c'], hm, snd)
            except KeyError:
                problems.append(f'answer not found: {sp["c"]} {hm} {snd}')
                continue
            txt = clean(am.get('content') or '') or '[图片]'
            parts.append(txt[:600])
            if snd not in repliers:
                repliers.append(snd)
        answer = '\n'.join(parts)
        replier = '、'.join(repliers) if repliers else 'AI助手'
        ai_reply = None
    else:
        answer = sp['ai']
        replier = 'AI助手'
        ai_reply = sp['ai']
    dt = '2026-10-13T' + qm['create_time'][11:16] + ':00+08:00'
    rec = {
        'Question': question[:1000],
        'Answer': answer[:2000],
        '提问人': asker,
        '回复人': replier,
        '问题日期': dt,
        '问题类型': sp['t'],
        '文本': raw[:2000],
    }
    if ai_reply:
        rec['AI回复'] = ai_reply[:2000]
    for k in ['Question', 'Answer', '提问人', '回复人', '问题类型', '问题日期']:
        if not rec.get(k):
            problems.append(f'EMPTY {k} in #{i} {sp["c"]} {sp["q"]}')
    records.append(rec)

print('QA records:', len(records))
print('problems:', problems)
ai_n = sum(1 for r in records if r.get('AI回复'))
print('AI answered:', ai_n, ' human answered:', len(records) - ai_n)
