import html

def esc(s):
    return html.escape(s, quote=False)

def entry(no, q, tags, items):
    lis = []
    for i, (head, body) in enumerate(items):
        seq = ' seq="1"' if i == 0 else ''
        inner = '<b>%s</b>：%s' % (esc(head), esc(body)) if head else esc(body)
        lis.append('<li%s>%s</li>' % (seq, inner))
    return ('<h3>%d. %s</h3>'
            '<p>| 标签： %s</p>'
            '<p><br/>回答：</p>'
            '<ol>%s</ol>') % (no, esc(q), esc(tags), ''.join(lis))

